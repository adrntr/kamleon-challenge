import uuid

from pydantic import AwareDatetime, BaseModel, ConfigDict, EmailStr, Field


class CustomerCreate(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True)

    name: str = Field(min_length=1, description="Full name.", examples=["Ana García"])
    email: EmailStr = Field(
        description="Contact email. Stored in lowercase; must not be registered yet.",
        examples=["ana@kamleon.com"],
    )


class CustomerRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID = Field(description="Customer id, generated by the server.")
    name: str = Field(description="Full name.", examples=["Ana García"])
    email: str = Field(description="Contact email, in lowercase.", examples=["ana@kamleon.com"])
    created_at: AwareDatetime = Field(description="Registration time.")
