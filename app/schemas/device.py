import uuid

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field

from app.domain.enums import DeviceStatus


class DeviceCreate(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True)

    serial_number: str = Field(
        min_length=1,
        description="Serial number printed on the device. Globally unique.",
        examples=["KM123"],
    )


class DeviceRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID = Field(description="Device id, generated by the server.")
    customer_id: uuid.UUID = Field(description="Id of the customer that owns the device.")
    serial_number: str = Field(description="Serial number of the device.", examples=["KM123"])
    status: DeviceStatus = Field(description="Whether the device accepts measurements.")
    created_at: AwareDatetime = Field(description="Registration time.")
    updated_at: AwareDatetime = Field(description="Last modification time.")


class DeviceList(BaseModel):
    items: list[DeviceRead] = Field(description="Devices, oldest first.")
