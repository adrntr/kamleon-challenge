import uuid
from typing import Literal

from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    ValidationError,
    field_validator,
)
from pydantic_core import InitErrorDetails, PydanticCustomError

from app.domain.measurements import BatchResult, ItemResult, ItemStatus, RejectionReason
from app.schemas.problem import PROBLEM_TYPE_BASE

# Bounds request size (~180 KB) and transaction duration; covers ~5 h of a
# device offline at 3 measurements/min. Far below Postgres's 65,535 bind
# parameters per statement (7 columns per row). See Batches in docs/DECISIONS.md.
MAX_BATCH_SIZE = 1000
# A typical page (~200 KB of JSON). See Querying measurements in docs/DECISIONS.md.
DEFAULT_QUERY_LIMIT = 1000
# ~1 MB of JSON; covers a full day of a device measuring 3 types per minute.
MAX_QUERY_LIMIT = 5000

# Per-item problem types: they only appear in results[].error.type, never as a top-level type.
ITEM_PROBLEM_TYPES: dict[RejectionReason, str] = {
    reason: PROBLEM_TYPE_BASE + reason.value for reason in RejectionReason
}
ItemProblemType = Literal[
    "https://api.kamleon.example/problems/unknown-type-unit",
    "https://api.kamleon.example/problems/measurement-id-conflict",
]


class MeasurementCreate(BaseModel):
    device_measurement_id: uuid.UUID = Field(
        description=(
            "Generated by the device when the measurement is taken, unique per device. "
            "Reused unchanged on every retry."
        ),
        examples=["0192a7c4-0001-7a3e-8b1f-3c2d4e5f6a70"],
    )
    type: str = Field(
        min_length=1,
        description="Measurement type. The (type, unit) pair must be registered.",
        examples=["ph"],
    )
    unit: str = Field(
        min_length=1,
        description="ASCII unit code, case-sensitive. The (type, unit) pair must be registered.",
        examples=["pH"],
    )
    value: float = Field(
        allow_inf_nan=False,
        description="Measured value. NaN and infinities are rejected.",
        examples=[7.41],
    )
    timestamp: AwareDatetime = Field(
        description="When the device took the measurement. Must include a UTC offset.",
        examples=["2026-10-06T09:00:00+02:00"],
    )


class MeasurementBatchCreate(BaseModel):
    measurements: list[MeasurementCreate] = Field(
        min_length=1,
        max_length=MAX_BATCH_SIZE,
        description=(
            f"1 to {MAX_BATCH_SIZE} measurements of this device. "
            "Each device_measurement_id may appear only once."
        ),
    )

    @field_validator("measurements")
    @classmethod
    def unique_device_measurement_ids(
        cls, measurements: list[MeasurementCreate]
    ) -> list[MeasurementCreate]:
        """Results are identified by device_measurement_id, so a repeated id is ambiguous."""
        seen: set[uuid.UUID] = set()
        errors: list[InitErrorDetails] = []
        for index, measurement in enumerate(measurements):
            if measurement.device_measurement_id in seen:
                errors.append(
                    InitErrorDetails(
                        type=PydanticCustomError(
                            "duplicate_device_measurement_id",
                            "device_measurement_id appears more than once in the batch",
                        ),
                        loc=(index, "device_measurement_id"),
                        input=measurement.device_measurement_id,
                    )
                )
            seen.add(measurement.device_measurement_id)
        if errors:
            raise ValidationError.from_exception_data(cls.__name__, errors)
        return measurements


class MeasurementItemError(BaseModel):
    type: ItemProblemType = Field(description="Problem type URI of the rejection.")
    detail: str = Field(
        description="Human-readable explanation.",
        examples=["Unit 'MA' is not registered for type 'current'"],
    )


class MeasurementItemResult(BaseModel):
    device_measurement_id: uuid.UUID = Field(description="Identifies the measurement.")
    status: ItemStatus = Field(
        description=(
            "created or duplicate: stored, remove it from the buffer. rejected: do not retry."
        )
    )
    error: MeasurementItemError | None = Field(
        default=None, description="Only present when status is rejected."
    )

    @classmethod
    def from_item(cls, item: ItemResult) -> MeasurementItemResult:
        error = None
        if item.rejection is not None:
            error = MeasurementItemError(
                type=ITEM_PROBLEM_TYPES[item.rejection.reason],  # type: ignore[arg-type]
                detail=item.rejection.detail,
            )
        return cls(
            device_measurement_id=item.device_measurement_id, status=item.status, error=error
        )


class MeasurementBatchSummary(BaseModel):
    received: int = Field(description="Measurements in the request.")
    created: int = Field(description="Stored by this request.")
    duplicate: int = Field(description="Already stored with the same payload (retries).")
    rejected: int = Field(description="Not stored; see results[].error.")


class MeasurementBatchRead(BaseModel):
    summary: MeasurementBatchSummary
    results: list[MeasurementItemResult] = Field(
        description="One entry per measurement, in request order."
    )

    @classmethod
    def from_result(cls, result: BatchResult) -> MeasurementBatchRead:
        return cls(
            summary=MeasurementBatchSummary(
                received=len(result.items),
                created=result.count(ItemStatus.CREATED),
                duplicate=result.count(ItemStatus.DUPLICATE),
                rejected=result.count(ItemStatus.REJECTED),
            ),
            results=[MeasurementItemResult.from_item(item) for item in result.items],
        )


class BatchRejectedProblem(BaseModel):
    """422 batch-rejected: problem details with the batch result as extension members."""

    type: Literal["https://api.kamleon.example/problems/batch-rejected"]
    title: str
    status: Literal[422]
    detail: str
    instance: str
    summary: MeasurementBatchSummary
    results: list[MeasurementItemResult]


class MeasurementQuery(BaseModel):
    """Query parameters of GET /devices/{device_id}/measurements."""

    type: str | None = Field(
        default=None, min_length=1, description="Only measurements of this type.", examples=["ph"]
    )
    from_: AwareDatetime | None = Field(
        default=None,
        alias="from",
        description=(
            "Start of the range, inclusive. Must include a UTC offset and be earlier than "
            "`to`. Defaults to `to` minus 24 hours."
        ),
        examples=["2026-10-06T00:00:00Z"],
    )
    to: AwareDatetime | None = Field(
        default=None,
        description="End of the range, exclusive. Must include a UTC offset. Defaults to now.",
        examples=["2026-10-07T00:00:00Z"],
    )
    limit: int = Field(
        default=DEFAULT_QUERY_LIMIT,
        ge=1,
        le=MAX_QUERY_LIMIT,
        description=f"Maximum number of measurements to return (1 to {MAX_QUERY_LIMIT}).",
    )


class MeasurementRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID = Field(description="Measurement id, generated by the server.")
    device_measurement_id: uuid.UUID = Field(description="Id generated by the device.")
    type: str = Field(description="Measurement type.", examples=["ph"])
    value: float = Field(description="Measured value.", examples=[7.41])
    unit: str = Field(description="ASCII unit code.", examples=["pH"])
    timestamp: AwareDatetime = Field(
        description="When the device took the measurement, in UTC.",
        examples=["2026-10-06T07:00:00Z"],
    )


class MeasurementList(BaseModel):
    items: list[MeasurementRead] = Field(
        description="Measurements in [from, to), oldest first, at most `limit`."
    )
    has_more: bool = Field(
        description="True if the range holds more measurements than `limit`: narrow the range."
    )
